@cl.on_chat_start
async def on_chat_start(accepted: bool = False):
    # SET UP RAG PIPELINE HERE!

    # display welcome and disclaimer
    subject = "SUBJECT HERE"
    descr = f"Hello! Welcome to {subject} Chatbot."
    subhead = f"I'm a chatbot designed to help you stay informed about {subject}. \n\nTo learn more, checkout the Readme page."
    disclaimer = f"{subject} Chatbot is an automated question answering tool, and is not intended to replace the advice of a qualified professional.\nContent generated by {subject} Chatbot is for informational purposes only."
    elements = [
        cl.Text(name=descr, content=subhead, display="inline"),
        cl.Text(name="Disclaimer", content=disclaimer, display="inline")
    ]
    await cl.Message(
        content='',
        elements=elements,
    ).send()

    res = {}
    # continue prompting until user selects 'I understand'
    while not accepted:
        res = await cl.AskActionMessage(
            content = f"Do you understand the purpose and limitations of {subject} Chatbot?",
            actions = [
                cl.Action(name="I understand", value="continue", label="I Understand", description="Agree and continue"),
                cl.Action(name="Disagree", value="disagree", label="Disagree", description="Disagree to terms of service")
            ],
            timeout = 300  # five minutes
        ).send()

        accepted = res.get("value") == "continue"

        if not accepted:
            await cl.Message(
                content = "You must agree to the terms of service to continue."
            ).send()
    
    welcome = f"Welcome! Ask me a question about {subject}, and I'll do my best to find you the most relevant and up-to-date information."

    await cl.Message(content=welcome).send()

    # set translator
    translator:BaseTranslator = get_translator()
    cl.user_session.set("translator", translator)

    # widget for translation language selection
    initial_lang_val = "Select Language"
    languages_to_iso_codes = translator.get_supported_languages(as_dict=True)
    language_values = [initial_lang_val] + [language.title() for language in languages_to_iso_codes.keys()]
    await cl.ChatSettings(
        [
            cl.input_widget.Select(  # language selector
                    id = "language",
                    label = "Language",
                    values = language_values,
                    initial_value = initial_lang_val,
            )
        ]
    ).send()


@cl.on_message
async def on_message(message: cl.Message):
    '''
    On user query: translates query to English, sends to OpenAI,
    returns OpenAI response translated into user language.
    '''
    start = time.time()
    translator:BaseTranslator = cl.user_session.get("translator")
    content = message.content

    # set translator if language is not English
    language = cl.user_session.get("language")
    if language != "en" and language is not None:
        content = await translate(translator, content, source=language, target="en")

